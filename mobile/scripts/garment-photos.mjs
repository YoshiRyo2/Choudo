// Writes src/components/mannequin/garment-photos.ts: a require() for every garment
// photo in the seed whose licence lets it ship in the app bundle. Run it after adding
// or re-licensing a photo: npm run photos -w @choudo/mobile
//
// local-only photos (cut-outs from photos we don't hold the rights to) are never
// required, so Metro never puts them in a build; they aren't committed either.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SHIPPABLE = new Set(['own', 'brand-permission', 'affiliate-unaltered']);

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const seed = JSON.parse(readFileSync(join(repo, 'packages/core/domain/garments/seed.json'), 'utf8'));
const out = join(here, '..', 'src/components/mannequin/garment-photos.ts');

const files = new Set();
for (const g of seed.garments) {
  for (const image of [g.image, g.backImage]) {
    if (image && SHIPPABLE.has(image.licence)) files.add(image.file);
  }
}
const sorted = [...files].sort();
const missing = sorted.filter((f) => !existsSync(join(repo, 'app/public', f)));
if (missing.length > 0) {
  console.error(`Not in app/public: ${missing.join(', ')}`);
  process.exit(1);
}

const lines = sorted.map((f) => `  '${f}': require('../../../../app/public/${f}'),`);
writeFileSync(
  out,
  `// Generated by \`npm run photos -w @choudo/mobile\` (scripts/garment-photos.mjs). Don't edit.
// Every garment photo whose licence lets it ship (own, brand-permission,
// affiliate-unaltered), keyed by its file in seed.json. local-only photos are left out.
import { Image } from 'react-native';

export const GARMENT_PHOTOS: Record<string, number> = {
${lines.join('\n')}
};

export interface PhotoSource {
  module: number;
  /** The photo's size in pixels: the space its landmarks are in. */
  width: number;
  height: number;
}

/** A bundled photo and its pixel size, or null when the file isn't bundled (draw the flat colour). */
export function photoSource(file: string): PhotoSource | null {
  const module = GARMENT_PHOTOS[file];
  if (module === undefined) return null;
  const resolved = Image.resolveAssetSource(module);
  if (!resolved?.width || !resolved?.height) return null;
  return { module, width: resolved.width, height: resolved.height };
}
`,
);
console.log(`Wrote ${sorted.length} photos to ${out}`);
