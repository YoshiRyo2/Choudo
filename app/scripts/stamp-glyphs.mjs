/**
 * One-off: outline ちょうど in Shippori Mincho B1 ExtraBold (800, SIL OFL 1.1,
 * https://github.com/fontdasu/ShipporiMincho) into SVG path data for the Fitting
 * room's stamp, so no Japanese font loads at runtime.
 *
 *   node scripts/stamp-glyphs.mjs [path/to/ShipporiMinchoB1-ExtraBold.ttf]
 *
 * With no path, the font is fetched from the google/fonts repository (about 15 MB,
 * kept in memory only). Writes packages/core/ui-logic/components/Stamp/stampGlyphs.ts (the path
 * the app draws) and packages/core/ui-logic/components/Stamp/stamp.svg (a reference preview).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const FONT_URL = 'https://raw.githubusercontent.com/google/fonts/main/ofl/shipporiminchob1/ShipporiMinchoB1-ExtraBold.ttf';
const OUT_DIR = new URL('../../packages/core/ui-logic/components/Stamp/', import.meta.url);

/** The stamp's box is 0..100 in both directions; the glyphs sit across its middle. */
const SIZE = 100;
const CENTRE = SIZE / 2;
/** The text's width: inside the inner ring (r 38.5) with room to spare. */
const TEXT_WIDTH = 68;
/** Each glyph's advance in em: the small ょ and the round う sit a little closer, as set by hand. */
const GLYPHS = [
  { char: 'ち', advance: 0.94 },
  { char: 'ょ', advance: 0.7 },
  { char: 'う', advance: 0.84 },
  { char: 'ど', advance: 1 },
];

async function loadFont() {
  const path = process.argv[2];
  if (path) return opentype.parse((await readFile(path)).buffer);
  const res = await fetch(FONT_URL);
  if (!res.ok) throw new Error(`Couldn't fetch the font: ${res.status} ${res.statusText}`);
  return opentype.parse(await res.arrayBuffer());
}

function layout(font, fontSize, dx, dy) {
  const path = new opentype.Path();
  let x = dx;
  for (const { char, advance } of GLYPHS) {
    const glyph = font.charToGlyph(char);
    if (!glyph || glyph.index === 0) throw new Error(`The font has no ${char}`);
    path.extend(glyph.getPath(x, dy, fontSize));
    x += advance * fontSize;
  }
  return path;
}

const font = await loadFont();
const ems = GLYPHS.reduce((sum, g) => sum + g.advance, 0);
const fontSize = TEXT_WIDTH / ems;
// Lay out once at the origin to measure the ink, then again centred on the box.
const box = layout(font, fontSize, 0, 0).getBoundingBox();
const dx = CENTRE - (box.x1 + box.x2) / 2;
const dy = CENTRE - (box.y1 + box.y2) / 2;
const d = layout(font, fontSize, dx, dy).toPathData(2);

const ts = `// Generated by scripts/stamp-glyphs.mjs: ちょうど outlined from Shippori Mincho B1 ExtraBold
// (800), SIL Open Font License 1.1, https://github.com/fontdasu/ShipporiMincho. Don't edit by hand.

/** The stamp's box: 0..${SIZE} square, centred on ${CENTRE}, ${CENTRE}. */
export const STAMP_BOX = ${SIZE};

/** ちょうど across the middle of the box, as one path. */
export const STAMP_GLYPHS = '${d}';
`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}">
  <!-- ちょうど: Shippori Mincho B1 ExtraBold, SIL OFL 1.1. Reference only: the app draws Stamp.tsx. -->
  <g fill="none" stroke="currentColor">
    <circle cx="${CENTRE}" cy="${CENTRE}" r="45" stroke-width="5.5"/>
    <circle cx="${CENTRE}" cy="${CENTRE}" r="38.5" stroke-width="1.6"/>
  </g>
  <path fill="currentColor" d="${d}"/>
</svg>
`;
await writeFile(new URL('stampGlyphs.ts', OUT_DIR), ts);
await writeFile(new URL('stamp.svg', OUT_DIR), svg);
console.log(`Wrote ${fileURLToPath(new URL('stampGlyphs.ts', OUT_DIR))} (${d.length} chars of path data)`);
